        <h2 class="text-xl font-semibold text-white sm:text-2xl">Evite os erros comuns</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Um erro frequente é subestimar a complexidade da integração com sistemas legados. Isso pode levar a um projeto falho, com custos elevados e atrasos. Outro ponto é a falta de alinhamento entre as expectativas de negócio e as capacidades técnicas. É crucial envolver todas as partes interessadas desde o início para evitar surpresas no meio do caminho.</p>
