      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Integrando IA sem grandes mudanças</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">A integração de IA em sistemas legados pode ser feita de maneira pragmática. É essencial avaliar quais partes da operação podem se beneficiar da IA sem exigir uma reestruturação completa. Por exemplo, a utilização de APIs pode facilitar a comunicação entre sistemas, permitindo que a IA seja aplicada onde faz mais sentido. Recentemente, soluções baseadas em IA têm mostrado resultados promissores em automação de processos e análise de dados, como discutido em [Modernizing KYC with AWS](https://aws.amazon.com/blogs/architecture/modernizing-kyc-with-aws-serverless-solutions-and-agentic-ai-for-financial-services/).</p>
