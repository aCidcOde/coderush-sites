        <h2 class="text-xl font-semibold text-white sm:text-2xl">Perguntas frequentes</h2>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Como calcular o ROI de um projeto de tecnologia?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Calcular o ROI envolve dividir o ganho líquido do projeto pelos custos totais, multiplicado por 100 para obter uma porcentagem. É importante incluir todos os custos, como desenvolvimento e manutenção.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Quais métricas usar para medir o sucesso de iniciativas de tecnologia?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">As métricas podem incluir aumento de receita, redução de custos, melhoria na eficiência operacional e satisfação do cliente. Cada iniciativa pode ter métricas específicas.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Como integrar IA em sistemas legados?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Integrar IA em sistemas legados exige uma análise cuidadosa. É importante mapear como a IA pode agregar valor sem interromper a operação atual. Uma abordagem gradual é recomendada.</p>
