        <h2 class="text-xl font-semibold text-white sm:text-2xl">Ferramentas e metodologias para decisão técnica</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Existem várias ferramentas e metodologias que podem ajudar na priorização. Por exemplo, o uso de frameworks de avaliação como o Business Model Canvas ou técnicas de priorização como o RICE (Reach, Impact, Confidence, Effort) podem tornar o processo mais ágil. Além disso, consultorias de tecnologia, como a CodeRush, têm experiência em ajudar empresas a adotar essas práticas de forma eficaz, garantindo que a decisão técnica seja embasada e sustentável.</p>
