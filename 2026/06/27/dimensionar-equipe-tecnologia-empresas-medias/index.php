      </p>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Erros a evitar no dimensionamento</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Um erro comum é não considerar a cultura organizacional ao dimensionar equipes. Equipes que não se alinham à cultura da empresa podem gerar resistência e problemas de comunicação. Além disso, negligenciar a integração com sistemas legados pode resultar em desafios operacionais significativos. Lembre-se de que um bom dimensionamento é tanto uma questão de números quanto de pessoas.</p>
      </section>
      <section class="mt-10">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Perguntas frequentes</h2>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Qual é o tamanho ideal de uma equipe de tecnologia?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">O tamanho ideal varia com a complexidade dos projetos e as necessidades da empresa, mas deve sempre buscar um equilíbrio entre eficiência e capacidade.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Como a governança impacta o dimensionamento da equipe?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Uma governança sólida ajuda a alinhar a equipe com os objetivos da empresa, garantindo que todos trabalhem em direção ao mesmo resultado e respeitem as regras de negócio.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Quais são os sinais de que a equipe está dimensionada incorretamente?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Sinais incluem atrasos em entregas, comunicação ineficaz e sobrecarga de trabalho para os membros da equipe. É crucial monitorar esses indicadores.</p>
        </details>
