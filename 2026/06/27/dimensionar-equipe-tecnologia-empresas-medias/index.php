      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">A importância do dimensionamento adequado</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">O dimensionamento de equipes de tecnologia é um desafio comum em empresas médias. Um estudo recente destaca que equipes muito grandes podem causar ineficiência, enquanto equipes pequenas podem não ter a capacidade de atender a todas as demandas ([Economia SP](https://economiasp.com/2023/10/03/dimensionamento-de-times-de-tecnologia/)). Portanto, entender as necessidades específicas da sua empresa é crucial.</p>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Critérios para dimensionamento eficaz</h2>
        <ul class="mt-4 space-y-2 text-sm leading-7 text-white/85 sm:text-base">
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Avalie a complexidade dos projetos em andamento.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Considere a habilidade técnica necessária.</span>
