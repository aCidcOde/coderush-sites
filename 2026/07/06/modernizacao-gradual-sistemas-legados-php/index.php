      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Por que modernizar sistemas legados?</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Sistemas legados muitas vezes são um obstáculo para a inovação. Eles podem ser difíceis de manter e integrar com novas tecnologias. Modernizar esses sistemas é crucial para manter a competitividade e permitir a implementação de soluções como IA e automação. Um processo gradual minimiza interrupções e garante que as operações críticas continuem funcionando.</p>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Sinais de que é hora de modernizar</h2>
        <ul class="mt-4 space-y-2 text-sm leading-7 text-white/85 sm:text-base">
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Dificuldade em integrar novas aplicações.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Alto custo de manutenção do sistema atual.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Necessidade frequente de adaptações urgentes.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Falta de documentação e suporte para o sistema.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-blue-400" aria-hidden="true"></span>
          <span>Baixa performance e instabilidade.</span>
        </li>
        </ul>
