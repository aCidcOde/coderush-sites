        <h2 class="text-xl font-semibold text-white sm:text-2xl">O que é pareamento humano-IA?</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">O pareamento humano-IA envolve a colaboração entre desenvolvedores e ferramentas de inteligência artificial, como o GitHub Copilot. Essa abordagem permite que os desenvolvedores aproveitem a capacidade da IA para gerar sugestões de código, enquanto mantêm o controle e a criatividade na implementação. A combinação dessas forças pode acelerar o ciclo de desenvolvimento, tornando o processo mais eficiente.</p>
