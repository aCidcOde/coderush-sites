        <li class="rounded-xl border border-white/10 bg-white/5 p-4 text-sm leading-6 text-white/90">Governança técnica é essencial para entregas rápidas.</li>
        <li class="rounded-xl border border-white/10 bg-white/5 p-4 text-sm leading-6 text-white/90">IA pode ser um grande aliado no desenvolvimento de software.</li>
        </ul>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">A importância da governança técnica</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Governança técnica é fundamental para garantir que os padrões de qualidade sejam seguidos durante o desenvolvimento de software sob medida. Isso envolve a definição de processos claros e a supervisão da qualidade do código. De acordo com [Pax Tecnologia](https://www.paxtecnologia.com.br/governanca-de-entrega/), é crucial estabelecer métricas que ajudem a monitorar a qualidade ao longo do ciclo de vida do software.</p>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Práticas para garantir qualidade</h2>
        <ul class="mt-4 space-y-2 text-sm leading-7 text-white/85 sm:text-base">
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Estabeleça critérios claros de aceitação.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Implemente testes automatizados desde o primeiro sprint.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Realize code reviews frequentes.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Utilize ferramentas de análise de código.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Aplique práticas ágeis para feedback contínuo.</span>
        </li>
        </ul>
      </section>
