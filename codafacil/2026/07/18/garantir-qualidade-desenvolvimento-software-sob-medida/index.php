          <p class="mt-2 text-sm leading-6 text-white/85">Os principais benefícios incluem melhor controle de qualidade, redução de retrabalho, e maior transparência nas entregas.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Como a IA pode ser aplicada no desenvolvimento de software?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">A IA pode ser utilizada para automação de testes, sugestões de código e análise de qualidade, o que melhora a eficiência do desenvolvimento.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">O que são testes automatizados?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Testes automatizados são scripts que verificam automaticamente se o código funciona como esperado, ajudando a identificar problemas rapidamente.</p>
