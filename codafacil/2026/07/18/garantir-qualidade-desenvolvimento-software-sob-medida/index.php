      </p>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Evite armadilhas comuns</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">É comum ver equipes subestimando a importância da documentação e da governança técnica, o que pode levar a problemas de qualidade no código. Além disso, não realizar testes automatizados pode resultar em retrabalho significativo. Para garantir sucesso, evite sacrificar a qualidade por prazos apertados.</p>
      </section>
      <section class="mt-10">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Perguntas frequentes</h2>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
