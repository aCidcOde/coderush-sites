      <aside class="mt-6 rounded-2xl border-l-4 border-sky-300 bg-white/[0.04] p-5 sm:p-6">
        <h3 class="text-sm font-semibold uppercase tracking-[0.18em] text-sky-300">Como gerenciar dívida técnica em produtos digitais?</h3>
        <p class="mt-2 text-base leading-7 text-white/90 sm:text-lg">Gerenciar dívida técnica envolve priorizar a manutenção do código, implementar testes automatizados e utilizar ferramentas de monitoramento. Uma abordagem contínua ajuda a evitar problemas futuros e melhora a experiência do desenvolvedor (DX).</p>
      </aside>
      <section class="mt-6">
        <p class="text-[11px] font-semibold uppercase tracking-[0.22em] text-white/55">Em resumo</p>
        <ul class="mt-3 grid gap-3 sm:grid-cols-3">
        <li class="rounded-xl border border-white/10 bg-white/5 p-4 text-sm leading-6 text-white/90">Priorize a manutenção do código para evitar problemas futuros.</li>
        <li class="rounded-xl border border-white/10 bg-white/5 p-4 text-sm leading-6 text-white/90">Implemente testes automatizados desde o início do projeto.</li>
        <li class="rounded-xl border border-white/10 bg-white/5 p-4 text-sm leading-6 text-white/90">Utilize ferramentas de monitoramento para uma melhor DX.</li>
        </ul>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Entendendo a Dívida Técnica</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">A dívida técnica é um conceito que se refere ao custo futuro de se optar por uma solução mais rápida em vez de uma mais robusta. Segundo a [Atlassian](https://www.atlassian.com/br/agile/software-development/technical-debt), é crucial reconhecer os sinais de dívida técnica, como código não documentado e falta de testes automatizados, para evitar que se tornem problemas maiores.</p>
      </section>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Sinais de Dívida Técnica</h2>
        <ul class="mt-4 space-y-2 text-sm leading-7 text-white/85 sm:text-base">
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Código não documentado ou mal documentado.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Falta de testes automatizados em novas funcionalidades.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Dificuldade em implementar novas features.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Dependências desatualizadas ou não utilizadas.</span>
        </li>
        <li class="flex gap-3">
          <span class="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-sky-300" aria-hidden="true"></span>
          <span>Problemas frequentes de performance.</span>
        </li>
        </ul>
      </section>
