      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Estratégias para Gerenciar Dívida Técnica</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Uma abordagem eficiente para gerenciar dívida técnica inclui a implementação de testes automatizados desde o primeiro sprint e o uso de IA para ajudar na revisão de código. Esse pareamento humano-IA, como com [GitHub Copilot](https://github.com/features/copilot), pode aumentar a eficiência e reduzir a introdução de novos débitos durante o desenvolvimento.</p>
      </section>
      <p class="my-6 text-sm leading-7 text-white/85 sm:text-base">
