      </p>
      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">O Que Evitar ao Gerenciar Dívida Técnica</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">É importante evitar a tentação de ignorar a dívida técnica, pois isso pode levar a um acúmulo significativo de problemas. Prioridades mal definidas e falta de comunicação entre equipes também podem contribuir para o agravamento da situação. Avalie constantemente o impacto da dívida técnica nas entregas e adapte as estratégias conforme necessário.</p>
      </section>
      <section class="mt-10">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Perguntas frequentes</h2>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">O que é dívida técnica?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Dívida técnica refere-se ao custo de escolher uma solução mais rápida, que pode resultar em mais problemas no futuro.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Como os testes automatizados ajudam na gestão da dívida técnica?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">Testes automatizados garantem que novas alterações não introduzam problemas, permitindo que a equipe mantenha a qualidade do código ao longo do tempo.</p>
        </details>
        <details class="mt-3 rounded-xl border border-white/10 bg-white/5 p-4">
          <summary class="cursor-pointer text-base font-semibold text-white">Qual o papel da IA na gestão de dívida técnica?</summary>
          <p class="mt-2 text-sm leading-6 text-white/85">A IA pode auxiliar na identificação de problemas no código e na revisão de alterações, tornando o processo de desenvolvimento mais eficiente.</p>
        </details>
