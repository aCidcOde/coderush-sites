      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">Onde isso pega numa operação de venda direta</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">Venda direta emite muita nota pequena: pedido de consultor, recompra, venda da loja virtual, assinatura. Quando a nota é emitida fora do sistema, cada mudança de layout vira retrabalho manual multiplicado pelo volume do mês. Quando é emitida pelo próprio sistema, a mudança fica concentrada em dois lugares: o cadastro de produtos e serviços, que passa a carregar a classificação tributária e o NBS, e a integração com a prefeitura ou com a SEFAZ, que passa a montar e assinar o XML no layout novo. É também ali que a nota de serviço de quem cobra mensalidade ou taxa de adesão precisa ser revista.</p>
