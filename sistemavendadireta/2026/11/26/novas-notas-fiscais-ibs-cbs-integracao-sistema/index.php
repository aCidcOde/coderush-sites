      <section class="mt-8">
        <h2 class="text-xl font-semibold text-white sm:text-2xl">O que mudou nas notas em 2026</h2>
        <p class="mt-3 text-sm leading-7 text-white/85 sm:text-base">A reforma tributária do consumo começou pela nota fiscal. Antes de o IBS e a CBS substituírem de fato os tributos atuais, eles passaram a ser informados nos documentos fiscais, com alíquotas de teste. Na NF-e e na NFC-e, o destaque passou a ser exigido das empresas do regime regular — lucro real e presumido — a partir de agosto de 2026, ainda com parte das regras de validação sendo ajustada pelo fisco. Na nota de serviço, os municípios passaram a ter de aderir ao padrão nacional da NFS-e, e São Paulo, que mantém sistema próprio, abriu em janeiro um segundo layout: o layout 1 continua só com ISS, e o layout 2 traz ISS, IBS e CBS, aceito pelo portal e pelo web service, mas não por arquivo TXT.</p>
